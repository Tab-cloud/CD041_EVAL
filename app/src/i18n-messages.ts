const dictionaries: Record<AppLanguage, Record<TranslationKey, string>> = { "zh-CN": zh, "en-US": en }

export function translate(language: AppLanguage, key: TranslationKey, values?: Record<string, string | number>): string {
  let result = dictionaries[language]?.[key] ?? zh[key]
  if (values) for (const [name, value] of Object.entries(values)) result = result.replaceAll(`{${name}}`, String(value))
  return result
}
