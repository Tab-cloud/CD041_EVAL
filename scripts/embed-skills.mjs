import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const skillsDir = join(root, "packages", "core", "src", "skills")
const output = join(skillsDir, "builtins.generated.ts")
const documents = readdirSync(skillsDir)
  .filter((name) => name.endsWith(".md"))
  .sort()
  .map((name) => readFileSync(join(skillsDir, name), "utf8"))

writeFileSync(
  output,
  `// Generated by scripts/embed-skills.mjs. Do not edit manually.\nexport const BUILTIN_SKILL_DOCUMENTS: string[] = ${JSON.stringify(documents, null, 2)}\n`,
  "utf8",
)
