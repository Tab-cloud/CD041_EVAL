import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const manifest = JSON.parse(readFileSync(join(root, "runtime-protocol.json"), "utf8"))
if (!Number.isSafeInteger(manifest.version) || manifest.version < 1) {
  throw new Error("runtime-protocol.json.version 必须是正整数")
}
if (!Array.isArray(manifest.events) || manifest.events.length === 0
  || manifest.events.some((event) => typeof event !== "string" || !/^[a-z][a-z-]*$/.test(event))) {
  throw new Error("runtime-protocol.json.events 必须是非空事件名称数组")
}
const source = `// Generated by scripts/generate-runtime-protocol.mjs. Do not edit.\nexport const RUNTIME_PROTOCOL_VERSION = ${manifest.version} as const\nexport const RUNTIME_EVENT_TYPES = ${JSON.stringify(manifest.events)} as const\nexport type RuntimeEventType = typeof RUNTIME_EVENT_TYPES[number]\n`
for (const target of [
  "packages/core/src/runtime/protocol.generated.ts",
  "app/src/runtime-protocol.generated.ts",
]) {
  writeFileSync(join(root, target), source, "utf8")
}
